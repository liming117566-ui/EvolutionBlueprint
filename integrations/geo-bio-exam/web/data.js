window.TOPICS = [];
function chapter(book, group, rows) {
  rows.forEach(r => {
    const id = book + '-' + (TOPICS.filter(t => t.book === book).length + 1);
    const [title, page, summary, facts, caution, quiz, scene] = r;
    const [question, correct, wrong1, wrong2] = quiz.split('|');
    const n = TOPICS.length % 3;
    const options = [correct, wrong1, wrong2];
    for (let i=0;i<n;i++) options.push(options.shift());
    TOPICS.push({id, book, group, title, page, summary, facts:facts.split('|'), caution, scene:scene||'concept', question, options, answer:(3-n)%3});
  });
}
